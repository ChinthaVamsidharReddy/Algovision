#!/usr/bin/env node
/**
 * Catalog sync generator.
 *
 * Reads packages/algorithms/content/<id>/ and writes the Flyway *repeatable* migration
 * apps/api/src/main/resources/db/migration/R__catalog_sync.sql, which upserts categories, topics and algorithms,
 * records one sha256 per language and appends an algorithm_versions row whenever the content hash changes.
 * Hashes are over newline-normalised raw source (solution file incl. anchor markers; algorithm.json), so any
 * change a learner could see changes the hash. Nothing is hard-coded to a placeholder.
 *
 * `--check` fails if the file on disk is missing or stale. Run `pnpm build:catalog` after editing content.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const contentDir = join(root, "packages/algorithms/content");
const outFile = join(root, "apps/api/src/main/resources/db/migration/R__catalog_sync.sql");
const languages = JSON.parse(readFileSync(join(root, "packages/algorithms/languages.json"), "utf8"));

/** Content category id -> catalog category + its single topic, from packages/algorithms/catalog.json (shared with the web app). */
const CATALOG = Object.fromEntries(
  JSON.parse(readFileSync(join(root, "packages/algorithms/catalog.json"), "utf8")).categories.map((c) => [c.id, c]),
);

const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const sha = (s) => createHash("sha256").update(s.replace(/\r\n/g, "\n")).digest("hex");
const read = (p) => readFileSync(p, "utf8");
const errors = [];

const dirs = readdirSync(contentDir).filter((d) => statSync(join(contentDir, d)).isDirectory()).sort();
const algos = dirs.map((id) => {
  const metaText = read(join(contentDir, id, "algorithm.json"));
  const meta = JSON.parse(metaText);
  const cat = CATALOG[meta.category];
  if (!cat) errors.push(`${id}: category "${meta.category}" has no catalog mapping in catalog-sync.mjs`);
  const langHashes = languages.map((l) => {
    const f = join(contentDir, id, `solution.${l.extension}`);
    if (!existsSync(f)) errors.push(`${id}: missing solution.${l.extension}`);
    return { code: l.id, hash: existsSync(f) ? sha(read(f)) : "" };
  });
  const version = sha([sha(metaText), ...langHashes.map((l) => `${l.code}:${l.hash}`)].join("\n"));
  return { id, meta, cat, langHashes, version };
});
if (errors.length) { console.error("catalog-sync:\n" + errors.map((e) => "  - " + e).join("\n")); process.exit(1); }

const lines = [
  "-- GENERATED by tools/content-compiler/catalog-sync.mjs - do not edit; run `pnpm build:catalog`.",
  "-- Flyway repeatable migration: re-applied whenever this file changes. Idempotent.",
  "",
];
const seen = new Set();
Object.values(CATALOG).forEach((c) => {
  if (!algos.some((a) => a.cat === c)) return;
  seen.add(c.slug);
  lines.push(
    `INSERT INTO categories (slug, name, description, status, sort_order) VALUES (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, 'PUBLISHED', ${c.sort})`,
    `ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, description = EXCLUDED.description, status = 'PUBLISHED', sort_order = EXCLUDED.sort_order;`,
    `INSERT INTO topics (category_id, slug, name, difficulty, summary, objectives, status, sort_order)`,
    `SELECT id, ${q(c.topic.slug)}, ${q(c.topic.name)}, ${q(c.topic.difficulty)}, ${q(c.topic.summary)}, ARRAY[${c.topic.objectives.map(q).join(", ")}], 'PUBLISHED', 10 FROM categories WHERE slug = ${q(c.slug)}`,
    `ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, difficulty = EXCLUDED.difficulty, summary = EXCLUDED.summary, objectives = EXCLUDED.objectives, status = 'PUBLISHED';`,
    "",
  );
});
algos.forEach((a, i) => {
  const m = a.meta;
  lines.push(
    `-- ${a.id}`,
    `INSERT INTO algorithms (topic_id, slug, content_key, name, state_kind, difficulty, summary, time_complexity, space_complexity, wave, status, sort_order)`,
    `SELECT id, ${q(a.id)}, ${q(a.id)}, ${q(m.title)}, ${q(m.stateKind)}, ${q(m.difficulty.toUpperCase())}, ${q(m.summary)}, ${q(m.complexity.time)}, ${q(m.complexity.space)}, ${m.wave}, 'PUBLISHED', ${(i + 1) * 10} FROM topics WHERE slug = ${q(a.cat.topic.slug)}`,
    `ON CONFLICT (slug) DO UPDATE SET topic_id = EXCLUDED.topic_id, name = EXCLUDED.name, state_kind = EXCLUDED.state_kind, difficulty = EXCLUDED.difficulty, summary = EXCLUDED.summary, time_complexity = EXCLUDED.time_complexity, space_complexity = EXCLUDED.space_complexity, wave = EXCLUDED.wave, status = 'PUBLISHED', sort_order = EXCLUDED.sort_order;`,
  );
  for (const l of a.langHashes) {
    lines.push(
      `INSERT INTO algorithm_languages (algorithm_id, language_code, content_hash) SELECT id, ${q(l.code)}, ${q(l.hash)} FROM algorithms WHERE slug = ${q(a.id)}`,
      `ON CONFLICT (algorithm_id, language_code) DO UPDATE SET content_hash = EXCLUDED.content_hash;`,
    );
  }
  lines.push(
    `INSERT INTO algorithm_versions (algorithm_id, version, content_hash, notes)`,
    `SELECT a.id, COALESCE((SELECT max(v.version) FROM algorithm_versions v WHERE v.algorithm_id = a.id), 0) + 1, ${q(a.version)}, 'content sync'`,
    `FROM algorithms a WHERE a.slug = ${q(a.id)}`,
    `AND COALESCE((SELECT v.content_hash FROM algorithm_versions v WHERE v.algorithm_id = a.id ORDER BY v.version DESC LIMIT 1), '') <> ${q(a.version)};`,
    "",
  );
});
const output = lines.join("\n");
if (process.argv.includes("--check")) {
  if (!existsSync(outFile) || read(outFile) !== output) { console.error("catalog-sync: R__catalog_sync.sql missing or stale; run `pnpm build:catalog`"); process.exit(1); }
  console.log(`catalog-sync: up to date (${algos.length} algorithms)`);
} else {
  if (!existsSync(outFile) || read(outFile) !== output) writeFileSync(outFile, output);
  console.log(`catalog-sync: ${algos.length} algorithms x ${languages.length} languages written`);
}
